/** Normalise any naming style to a lucide-style kebab key: "LifeBuoy" / "life_buoy" → "life-buoy". */
export function iconKey(name: string): string {
  return name
    .trim()
    .replace(/Icon$/, "")
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([A-Z])([A-Z][a-z])/g, "$1-$2")
    .replace(/([a-zA-Z])(\d)/g, "$1-$2")
    .replace(/[\s_.:/]+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "")
    .toLowerCase();
}

const ICONS = new globalThis.Map<string, LucideIcon>();
for (const [icon, names] of TABLE) for (const n of names) if (!ICONS.has(iconKey(n))) ICONS.set(iconKey(n), icon);

/** Resolve a starter's icon name to a lucide icon (never throws; unknown → chat glyph). */
export function starterIcon(name: string | null | undefined): LucideIcon {
  if (!name) return DEFAULT_STARTER_ICON;
  const key = iconKey(name);
  return ICONS.get(key) ?? DEFAULT_STARTER_ICON;
}
